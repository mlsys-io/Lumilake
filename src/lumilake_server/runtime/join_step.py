"""Standalone join step: merge row columns and 1:1 outputs onto keyed rows.

The generated task carries its whole description in ``_JOIN``, so its source
holds no user code.
"""

import json

from lumilake_server.data_specs import ColumnPlanEntry, JoinDescription


def join_source(
    op_id: str,
    description: JoinDescription,
    plan: list[ColumnPlanEntry],
    runtime_mount: str,
) -> str:
    """The python-task code for one lowered join."""
    return _PRELUDE.format(
        op_id=op_id,
        module="lumilake_runtime",
        mount=runtime_mount,
        join=json.dumps(description.model_dump(), ensure_ascii=False),
        plan=json.dumps(
            [entry.model_dump(exclude_none=True) for entry in plan],
            ensure_ascii=False,
        ),
    )


_PRELUDE = '''\
# Generated by Lumilake for JoinOp {op_id!r}: a keyed join over row columns.
import importlib.util
import json

_SPEC = importlib.util.spec_from_file_location({module!r}, {mount!r})
_RUNTIME = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(_RUNTIME)
_column = _RUNTIME._column
_decoded_cell = _RUNTIME._decoded_cell
_decoded_rows = _RUNTIME._decoded_rows
failure_of = _RUNTIME.failure_of
carried_marker = _RUNTIME.carried_marker
_PLAN = json.loads({plan!r})
_JOIN = json.loads({join!r})

_NODE = _JOIN["node"]
_BY = _JOIN["by"]
_ON_MISSING = _JOIN["on_missing"]


def _named(entry):
    """A plan entry's name, for an error message."""
    return entry.get("node", "literal")


def _where(entry):
    return "%s input %r" % (_NODE, _named(entry))


def _rows(column, where):
    """The row objects a column holds, one per row."""
    rows = []
    for item in column:
        rows.extend(_decoded_rows(_decoded_cell(item), where))
    return rows


def _key(row, where):
    """A row's join key, from its dotted key path; a row without the field
    fails the job."""
    value = _value(row, ".".join(_BY))
    if value is None:
        raise ValueError("%s: row has no key field %r" % (where, ".".join(_BY)))
    return _encoded(value, where)


def _encoded(value, where):
    try:
        return json.dumps(value, sort_keys=True)
    except TypeError:
        raise ValueError("%s: key %r is not a JSON value" % (where, value))


def _value(row, path):
    """The value a dotted field path names in one row, or ``None`` when the
    row lacks a field of the path or the path reaches a marker."""
    value = row
    for part in path.split("."):
        if not isinstance(value, dict) or part not in value:
            return None
        value = value[part]
        if failure_of(value) is not None:
            return None
    return value


def _failed(reason):
    """One marker for a row the join cannot place, naming the join and why."""
    return {{"_fail": {{"op": _NODE, "reason": reason}}}}


def _key_of(row, where):
    """The row's key, or ``None`` when a failed record leaves it without one:
    the row is itself a marker, or its key path reaches a marker or a field the
    row lacks. A row whose key reads keeps that key even when another of its
    fields is a marker."""
    value = _value(row, ".".join(_BY))
    if value is None:
        return None
    return _encoded(value, where)


def _merged(merged, field, value, where):
    if field in merged and merged[field] != value:
        raise ValueError(
            "%s: field %r conflicts between %r and an earlier input"
            % (_NODE, field, where)
        )
    merged[field] = value


def _merge(row, more, where):
    for name, value in more.items():
        _merged(row, name, value, where)


def _required(keyed, keys, where):
    """Fail the job when a further input carries a key the first input does
    not, so a stray or misspelt row never loses its fields unnoticed."""
    for key in keys:
        if key not in keyed:
            raise ValueError("%s: key %s is not in %r" % (_NODE, key, where))


def _keyed(rows, where):
    """One further input's rows by key. A marked row keeps its key and marks it;
    a row whose key cannot be read fails the job, since it cannot be placed."""
    keyed = {{}}
    marked = {{}}
    for row in rows:
        key = _key_of(row, where)
        if key is None:
            raise ValueError(
                "%s: a failed row whose key cannot be read cannot be placed" % where
            )
        if key in keyed:
            raise ValueError("%s: duplicate key %s" % (where, key))
        keyed[key] = row
        carried = carried_marker((row,))
        if carried is not None:
            marked[key] = carried
    return keyed, marked


def _attach(keyed, marked, name, source_index, values, rows, where):
    """Merge one attach field's values onto the source rows by position. A
    source row or value that carries a failed record marks that key's output
    instead of filling its field. The value column pairs with every source row
    when its length matches, or with the live rows only; any other length
    cannot be attributed to one row, so it fails the job. A first-input key no
    pair reaches is marked under ``fail_row`` and keeps its field out under
    ``null_fill``."""
    live = []
    for row in rows:
        carried = carried_marker((row,))
        if carried is None:
            live.append(row)
            continue
        key = _key_of(row, where)
        if key is not None and key not in marked:
            # The source row's own failed record is its key's output, unless
            # another marker already holds that key.
            marked[key] = carried
    if len(values) == len(rows):
        # A row whose key cannot be read is already its own marker, and its
        # value is the marker passed through: there is no key to pair it with.
        pairs = [
            (value, key)
            for value, key in zip(values, (_key_of(row, where) for row in rows))
            if key is not None
        ]
    elif len(values) == len(live):
        pairs = list(zip(values, (_key(row, where) for row in live)))
    else:
        raise ValueError(
            "%s: %d values attached but %d rows from %r"
            % (_NODE, len(values), len(rows), _named(_PLAN[source_index]))
        )
    paired = dict.fromkeys(key for _, key in pairs)
    _required(keyed, paired, where)
    for value, key in pairs:
        if key in marked:
            continue
        carried = failure_of(value)
        if carried is not None:
            marked[key] = carried
            continue
        _merged(keyed[key], name, value, where)
    return paired


def main(inputs):
    indexes = _JOIN["inputs"]
    columns = [_column(_PLAN[index], inputs, _decoded_cell) for index in indexes]
    first = _where(_PLAN[indexes[0]])
    rows = _rows(columns[0], first)
    keyed = {{}}
    marked = {{}}
    for row in rows:
        carried = carried_marker((row,))
        # The first input still emits one row per its row: a marked row whose
        # key cannot be read emits its marker at its own position, and a live
        # row without a key fails the job.
        key = _key_of(row, first) if carried is not None else _key(row, first)
        if key is None:
            continue
        if key in keyed:
            raise ValueError("%s: duplicate key %s" % (first, key))
        keyed[key] = row
        if carried is not None:
            marked[key] = carried
    for index, column in zip(indexes[1:], columns[1:]):
        where = _where(_PLAN[index])
        more, more_marked = _keyed(_rows(column, where), where)
        _required(keyed, more, where)
        missing = [key for key in keyed if key not in more]
        if missing and _ON_MISSING == "fail_row":
            # Only the row whose key a further input lacks becomes a marker;
            # the other rows merge as usual.
            for key in missing:
                if key not in marked:
                    marked[key] = _failed("key %s is missing from %r" % (key, where))
        for key in more:
            if key in marked:
                # A marked row's output is its marker: its other fields and
                # every further input for that key are skipped.
                continue
            if key in more_marked:
                marked[key] = more_marked[key]
                continue
            _merge(keyed[key], more[key], where)
    for name, value_index, source_index in _JOIN["attach"]:
        where = "%s attach field %r" % (_NODE, name)
        values = [
            _decoded_cell(value)
            for value in _column(_PLAN[value_index], inputs, _decoded_cell)
        ]
        more = _rows(_column(_PLAN[source_index], inputs, _decoded_cell), where)
        paired = _attach(keyed, marked, name, source_index, values, more, where)
        if _ON_MISSING == "fail_row":
            # Only a row the attach source lacks a key for becomes a marker;
            # under null_fill its field is simply left out.
            for key in keyed:
                if key not in paired and key not in marked:
                    marked[key] = _failed("key %s is missing from %r" % (key, where))
    items = []
    for row in rows:
        key = _key_of(row, first)
        output = carried_marker((row,)) if key is None else marked.get(key, keyed[key])
        items.append({{"output": output}})
    return {{"items": items}}
'''
