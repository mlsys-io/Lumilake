"""Standalone join step: merge row columns and 1:1 outputs onto keyed rows.

A ``JoinOp`` lowers to one FlowMesh ``python`` task whose ``main`` reads one
plan column per join input and one value/source pair per attach field, then
merges them by the join key. The task carries its whole description in
``_JOIN``, so the generated source holds no user code: the first input fixes
the output rows, every further input contributes the fields of the row with the
same key, and each attach value lands on the source row it was computed from.
"""

import json
from typing import Any

JOIN_MODE = "join"


def join_source(op_id: str, description: dict[str, Any], plan: list[Any]) -> str:
    """The python-task code for one lowered join."""
    return _PRELUDE.format(
        op_id=op_id,
        module="lumilake_runtime",
        mount="/mnt/blobs/lumilake-runtime.py",
        join=json.dumps(description, ensure_ascii=False),
        plan=json.dumps(plan, ensure_ascii=False),
    )


_PRELUDE = '''\
# Generated by Lumilake for JoinOp {op_id!r}: a keyed join over row columns.
import importlib.util
import json

_SPEC = importlib.util.spec_from_file_location({module!r}, {mount!r})
_RUNTIME = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(_RUNTIME)
_column = _RUNTIME._column
_decoded_cell = _RUNTIME._decoded_cell
_decoded_rows = _RUNTIME._decoded_rows
_PLAN = json.loads({plan!r})
_JOIN = json.loads({join!r})

_NODE = _JOIN["node"]
_BY = _JOIN["by"]
_MISSING = _JOIN["missing"]


def _named(entry):
    """A plan entry's name, for an error message."""
    return entry.get("node", "literal")


def _where(entry):
    return "%s input %r" % (_NODE, _named(entry))


def _rows(column, where):
    """The row objects a column holds, one per row."""
    rows = []
    for item in column:
        rows.extend(_decoded_rows(_decoded_cell(item)))
    return rows


def _key(row, where):
    value = row
    for part in _BY:
        if not isinstance(value, dict) or part not in value:
            raise ValueError("%s: row has no key field %r" % (where, part))
        value = value[part]
    try:
        return json.dumps(value, sort_keys=True)
    except TypeError:
        raise ValueError("%s: key %r is not a JSON value" % (where, value))


def _keyed(rows, where):
    keyed = {{}}
    for row in rows:
        key = _key(row, where)
        if key in keyed:
            raise ValueError("%s: duplicate key %s" % (where, key))
        keyed[key] = row
    return keyed


def _required(output, keys, where):
    """Fail the job when ``error`` is set and a join row the column does not
    carry would silently lose its fields."""
    if _MISSING != "error":
        return
    for key in output:
        if key not in keys:
            raise ValueError("%s: key %s is missing from %r" % (_NODE, key, where))


def _merged(merged, field, value, where):
    if field in merged and merged[field] != value:
        raise ValueError(
            "%s: field %r conflicts between %r and an earlier input"
            % (_NODE, field, where)
        )
    merged[field] = value


def main(inputs):
    indexes = _JOIN["inputs"]
    columns = [_column(_PLAN[index], inputs, _decoded_cell) for index in indexes]
    first = _where(_PLAN[indexes[0]])
    output = _keyed(_rows(columns[0], first), first)
    for index, column in zip(indexes[1:], columns[1:]):
        where = _where(_PLAN[index])
        keyed = _keyed(_rows(column, where), where)
        _required(output, keyed, where)
        for key, row in keyed.items():
            if key in output:
                for name, value in row.items():
                    _merged(output[key], name, value, where)
    for name, value_index, source_index in _JOIN["attach"]:
        where = "%s attach field %r" % (_NODE, name)
        values = _column(_PLAN[value_index], inputs, _decoded_cell)
        rows = _rows(_column(_PLAN[source_index], inputs, _decoded_cell), where)
        if len(values) != len(rows):
            raise ValueError(
                "%s: %d values from %r but %d rows from %r"
                % (
                    _NODE,
                    len(values),
                    _named(_PLAN[value_index]),
                    len(rows),
                    _named(_PLAN[source_index]),
                )
            )
        keys = [_key(row, where) for row in rows]
        _required(output, dict.fromkeys(keys), where)
        for value, key in zip(values, keys):
            if key in output:
                _merged(output[key], name, value, where)
    return {{"items": [{{"output": row}} for row in output.values()]}}
'''
