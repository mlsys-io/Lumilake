"""Standalone Python steps: a LambdaOp that no LLM consumes.

A LambdaOp that is an output, or feeds only other LambdaOps, runs as its own
FlowMesh ``python`` task in a per-task container.
"""

import copy
import hashlib
import inspect
import json
from collections.abc import Mapping
from dataclasses import dataclass
from functools import cache
from typing import Any
from urllib.parse import quote

from lumilake import envs
from lumilake_server.runtime import lambda_task_helpers
from lumilake_server.utils import lambda_runtime

TASK_RUNTIME_MOUNT = "/mnt/blobs/lumilake-runtime.py"
TASK_RUNTIME_MODULE = "lumilake_runtime"
LITERAL_INLINE_MAX_BYTES = 1024
LITERAL_MOUNT_ROOT = "/mnt/blobs/literals"

TASK_TYPE = "python"
BACKEND = "python"
DEFAULT_TIMEOUT_SECONDS = 600

# Column plan entries: {"kind": "stage", "node": <upstream node id>} or
# {"kind": "literal", "values": [...]}.
ColumnPlan = list[dict[str, Any]]


@dataclass(frozen=True)
class PublishedBlob:
    key: str
    object_name: str
    body: bytes
    content_type: str
    sha256: str
    mount_path: str


_PRELUDE = """\
# Generated by Lumilake for LambdaOp {op_id!r}. The caller's function is
# _USER_CODE; the mounted runtime adapts it to a FlowMesh python task.
import importlib.util
import json

_SPEC = importlib.util.spec_from_file_location({module!r}, {mount!r})
_RUNTIME = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(_RUNTIME)
_text = _RUNTIME._text
_column = _RUNTIME._column
materialize = _RUNTIME.materialize

_USER_CODE = {code!r}
_FN_NAME = {fn_name!r}
_PLAN = json.loads({plan!r})
"""

_RESHAPE_PRELUDE = """\
# Generated by Lumilake for {op_id!r}: a flatten/regroup reshape step.
import importlib.util
import json

_SPEC = importlib.util.spec_from_file_location({module!r}, {mount!r})
_RUNTIME = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(_RUNTIME)
_text = _RUNTIME._text
_column = _RUNTIME._column
_NODE = {op_id!r}
_PLAN = json.loads({plan!r})
"""

_FLATTEN_MAIN = """\

_TEMPLATE = {template!r}

def main(inputs):
    columns = [_column(entry, inputs, _text) for entry in _PLAN]
    grouped = [c for c, e in zip(columns, _PLAN) if e.get("grouped")]
    row_level = [c for c, e in zip(columns, _PLAN) if not e.get("grouped")]
    n = len(grouped[0])
    group_sizes = [len(g) for g in grouped[0]]
    for entry, col in zip(_PLAN, columns):
        label = entry.get("label")
        if entry.get("grouped"):
            if len(col) != n:
                raise ValueError(
                    "%s: flatten grouped column %r has %d groups; expected %d"
                    % (_NODE, label, len(col), n)
                )
            for i, group in enumerate(col):
                if len(group) != group_sizes[i]:
                    raise ValueError(
                        "%s: flatten grouped column %r row %d has %d values; "
                        "expected %d" % (_NODE, label, i, len(group), group_sizes[i])
                    )
        elif len(col) not in (1, n):
            raise ValueError(
                "%s: flatten row-level column %r has %d values; expected 1 or %d"
                % (_NODE, label, len(col), n)
            )
    items = []
    for i in range(n):
        size = group_sizes[i]
        for j in range(size):
            values = {{}}
            for entry, col in zip(_PLAN, columns):
                if entry is _PLAN[0]:
                    # The image entry (always first) is the group boundary; its
                    # content is never rendered into the prompt.
                    continue
                label = entry.get("label")
                if entry.get("grouped"):
                    values[label] = col[i][j]
                else:
                    values[label] = col[i] if len(col) == n else col[0]
            prompt = _TEMPLATE.format_map(
                {{k: _text(v) for k, v in values.items()}}
            )
            items.append({{"output": prompt, "row": i}})
    return {{"items": items}}
"""

_REGROUP_MAIN = """\

def main(inputs):
    columns = [_column(entry, inputs, _text) for entry in _PLAN]
    values = columns[0]
    rows = columns[1]
    groups = columns[2]
    n = len(groups)
    if len(values) != len(rows):
        raise ValueError(
            "%s: regroup has %d outputs but %d rows" % (_NODE, len(values), len(rows))
        )
    result = [[] for _ in range(n)]
    for value, row in zip(values, rows):
        if not isinstance(row, int):
            raise ValueError("%s: regroup row %r is not an integer" % (_NODE, row))
        if not 0 <= row < n:
            raise ValueError(
                "%s: regroup row %d out of range for %d symbols" % (_NODE, row, n)
            )
        result[row].append(value)
    for r in range(n):
        if len(result[r]) != len(groups[r]):
            raise ValueError(
                "%s: regroup row %d has %d outputs; expected %d"
                % (_NODE, r, len(result[r]), len(groups[r]))
            )
    return {{"items": [{{"output": result[r]}} for r in range(n)]}}
"""

_PAIRS_MAIN = """\

def main(inputs):
    columns = [_column(entry, inputs, lambda v: v) for entry in _PLAN]
    queries, candidates = columns
    if len(queries) == 1:
        queries = queries * len(candidates)
    if len(queries) != len(candidates):
        raise ValueError(
            "%s: query column has %d values but candidate column has %d"
            % (_NODE, len(queries), len(candidates))
        )
    return {{"items": [
        {{"text": query, "text_pair": candidate}}
        for query, candidate in zip(queries, candidates)
    ]}}
"""

_ROW_MAIN = """\

def main(inputs):
    fn = materialize(_USER_CODE, _FN_NAME)
    columns = [_column(entry, inputs, _text) for entry in _PLAN]
    n = max((len(c) for c in columns), default=1)
    for entry, col in zip(_PLAN, columns):
        if len(col) not in (1, n):
            raise ValueError(
                "input %r has %d rows; expected 1 or %d"
                % (entry.get("node", "literal"), len(col), n)
            )
    rows = [tuple(c[0] if len(c) == 1 else c[i] for c in columns) for i in range(n)]
    return {{
        "items": [
            {{"output": _text(r), "value": r}}
            for r in (fn(row) for row in rows)
        ]
    }}
"""

_ROW_STATUS_MAIN = """\

def main(inputs):
    columns = [_column(entry, inputs, lambda v: v) for entry in _PLAN]
    n = max((len(c) for c in columns), default=0)
    for entry, col in zip(_PLAN, columns):
        if len(col) not in (1, n):
            raise ValueError(
                "input %r has %d rows; expected 1 or %d"
                % (entry.get("node", "literal"), len(col), n)
            )
    rules = {rules}
    statuses = []
    for i in range(n):
        row = {}
        for entry, col in zip(_PLAN, columns):
            value = col[0] if len(col) == 1 else col[i]
            if isinstance(value, str):
                try:
                    value = json.loads(value)
                except ValueError:
                    pass
            row[entry.get("label", "value")] = value
        source_value = row.get("route", row.get("source", row.get("value", "")))
        if isinstance(source_value, dict):
            source_value = json.dumps(source_value)
        if not isinstance(source_value, str):
            source_value = json.dumps(source_value)
        branch = {default_branch}
        for rule in rules:
            if rule["match"] == "equals":
                matched = source_value == rule["value"]
            else:
                matched = rule["value"] in source_value
            if matched:
                branch = rule["branch"]
                break
        statuses.append(
            {
                "output": json.dumps(
                    {
                        "selected": True,
                        "done": {terminal} and branch == {terminal_branch},
                        "branch": branch,
                        "row": i,
                    }
                ),
                "value": {
                    "selected": True,
                    "done": {terminal} and branch == {terminal_branch},
                    "branch": branch,
                    "row": i,
                },
            }
        )
    return {"items": statuses}
"""

_ROW_SKIP_MERGE_MAIN = """\

def main(inputs):
    columns = [_column(entry, inputs, lambda v: v) for entry in _PLAN]
    statuses = columns[0]
    outputs = columns[1]
    if not outputs:
        return {"items": []}
    selected = []
    for index, value in enumerate(statuses):
        if isinstance(value, str):
            try:
                value = json.loads(value)
            except ValueError:
                pass
        if not isinstance(value, dict):
            raise ValueError("row status %d is not an object" % index)
        if value.get("branch") == {branch}:
            selected.append(value)
    if len(selected) != len(outputs):
        raise ValueError(
            "%s: merged %d outputs for %d selected rows"
            % (_NODE, len(outputs), len(selected))
        )
    output_index = 0
    merged = []
    for status in statuses:
        value = status
        if isinstance(value, str):
            try:
                value = json.loads(value)
            except ValueError:
                pass
        row = dict(value)
        if row.get("done"):
            continue
        if row.get("branch") == {branch}:
            row["output"] = outputs[output_index]
            output_index += 1
        else:
            row["output"] = None
        merged.append({"output": json.dumps(row), "value": row})
    return {"items": merged}
"""

_ROW_SELECT_MAIN = """\

def main(inputs):
    columns = [_column(entry, inputs, lambda v: v) for entry in _PLAN]
    statuses = columns[0]
    labels = _LABELS
    selected = []
    for index, value in enumerate(statuses):
        if isinstance(value, str):
            try:
                value = json.loads(value)
            except ValueError:
                pass
        if not isinstance(value, dict):
            raise ValueError("row status %d is not an object" % index)
        if value.get("done") and not {include_done}:
            continue
        if value.get("branch") != {branch}:
            continue
        row = {}
        for label, column in zip(labels, columns[1:]):
            row[label] = column[0] if len(column) == 1 else column[index]
        selected.append(row)
    return {"items": selected}
"""

_LIST_MAIN = """\

def main(inputs):
    fn = materialize(_USER_CODE, _FN_NAME)
    columns = [_column(entry, inputs, lambda v: v) for entry in _PLAN]
    values = fn(tuple(columns))
    return {{"items": [{{"output": v}} for v in values]}}
"""

_ALIGNED_MAIN = """\

def main(inputs):
    fn = materialize(_USER_CODE, _FN_NAME)
    columns = [_column(entry, inputs, lambda v: v) for entry in _PLAN]
    n = max((len(c) for c in columns), default=0)
    for entry, col in zip(_PLAN, columns):
        if len(col) not in (1, n):
            raise ValueError(
                "input %r has %d rows; expected 1 or %d"
                % (entry.get("node", "literal"), len(col), n)
            )
    values = fn(tuple(columns))
    if len(values) != n:
        raise ValueError(
            "aligned lambda {op_id!r} returned %d values for %d rows"
            % (len(values), n)
        )
    return {{"items": [{{"output": v}} for v in values]}}
"""


def flatten_source(node_id: str, plan: ColumnPlan, template: str) -> str:
    """The python-task code for a flatten step: one rendered prompt per image."""
    return (_RESHAPE_PRELUDE + _FLATTEN_MAIN).format(
        op_id=node_id,
        module=TASK_RUNTIME_MODULE,
        mount=TASK_RUNTIME_MOUNT,
        plan=json.dumps(plan),
        template=template,
    )


def regroup_source(node_id: str, plan: ColumnPlan) -> str:
    """The python-task code for a regroup step: outputs back to one item per
    symbol."""
    return (_RESHAPE_PRELUDE + _REGROUP_MAIN).format(
        op_id=node_id,
        module=TASK_RUNTIME_MODULE,
        mount=TASK_RUNTIME_MOUNT,
        plan=json.dumps(plan),
    )


def pairs_source(node_id: str, plan: ColumnPlan) -> str:
    """The python-task code for reshaping query and candidate columns to pairs."""
    return (_RESHAPE_PRELUDE + _PAIRS_MAIN).format(
        op_id=node_id,
        module=TASK_RUNTIME_MODULE,
        mount=TASK_RUNTIME_MOUNT,
        plan=json.dumps(plan),
    )


def row_skip_merge_code(
    node_id: str,
    plan: ColumnPlan,
    *,
    branch: str,
) -> str:
    """Generated list-mode step that merges gated rows back into one list."""
    prelude = _RESHAPE_PRELUDE.format(
        op_id=node_id,
        module=TASK_RUNTIME_MODULE,
        mount=TASK_RUNTIME_MOUNT,
        plan=json.dumps(plan),
    )
    return prelude + _ROW_SKIP_MERGE_MAIN.replace("{branch}", repr(branch))


def row_select_source(
    node_id: str,
    plan: ColumnPlan,
    *,
    labels: list[str],
    branch: str,
    include_done: bool = False,
) -> str:
    """Generated list-mode step that keeps only one routed branch."""
    prelude = _RESHAPE_PRELUDE.format(
        op_id=node_id,
        module=TASK_RUNTIME_MODULE,
        mount=TASK_RUNTIME_MOUNT,
        plan=json.dumps(plan),
    )
    prelude += f"\n_LABELS = {labels!r}\n"
    main = (
        _ROW_SELECT_MAIN.replace("{_LABELS}", "_LABELS")
        .replace("{branch}", repr(branch))
        .replace("{include_done}", repr(include_done))
    )
    return prelude + main


def row_status_source(
    node_id: str,
    plan: ColumnPlan,
    *,
    rules: list[dict[str, str]],
    default_branch: str,
    terminal_branch: str | None = None,
) -> str:
    """Generated row-status step with the router rules rendered directly."""
    rendered_rules = ",\n        ".join(repr(rule) for rule in rules)
    main = _ROW_STATUS_MAIN.replace(
        "rules = {rules}",
        f"rules = [\n        {rendered_rules},\n    ]",
    )
    main = main.replace("{default_branch}", repr(default_branch))
    main = main.replace("{terminal_branch}", repr(terminal_branch or ""))
    main = main.replace("{terminal}", "True" if terminal_branch else "False")
    return (
        _PRELUDE.format(
            op_id=node_id,
            module=TASK_RUNTIME_MODULE,
            mount=TASK_RUNTIME_MOUNT,
            code="",
            fn_name="row_status",
            plan=json.dumps(plan),
        )
        + main
    )


@cache
def runtime_blob() -> PublishedBlob:
    """The worker-side runtime source mounted by every generated task."""
    body = (
        inspect.getsource(lambda_runtime)
        + "\n\n"
        + inspect.getsource(lambda_task_helpers)
    ).encode("utf-8")
    digest = hashlib.sha256(body).hexdigest()
    key = f"lambda-runtime/{digest}.py"
    return PublishedBlob(
        key=key,
        object_name=key,
        body=body,
        content_type="text/x-python",
        sha256=digest,
        mount_path=TASK_RUNTIME_MOUNT,
    )


def literal_blob(entry: dict[str, Any]) -> PublishedBlob | None:
    """The mounted blob for one literal entry, or None when it stays inline."""
    encoded = json.dumps(entry["values"], ensure_ascii=False).encode("utf-8")
    if len(encoded) <= LITERAL_INLINE_MAX_BYTES:
        return None
    digest = hashlib.sha256(encoded).hexdigest()
    key = f"literals/{digest}.json"
    return PublishedBlob(
        key=key,
        object_name=key,
        body=encoded,
        content_type="application/json",
        sha256=digest,
        mount_path=f"{LITERAL_MOUNT_ROOT}/{digest}.json",
    )


def literal_blobs(plan: ColumnPlan) -> dict[str, PublishedBlob]:
    """Content-addressed JSON blobs for literal payloads above the inline cutoff."""
    blobs: dict[str, PublishedBlob] = {}
    for entry in plan:
        if entry["kind"] != "literal":
            continue
        blob = literal_blob(entry)
        if blob is not None:
            blobs[blob.key] = blob
    return blobs


def blob_url(object_name: str) -> str:
    base = envs.LUMID_DATA_WORKER_URL or envs.LUMID_DATA_URL
    if not base:
        raise RuntimeError("LUMID_DATA_URL is required for LambdaOp task blobs")
    return f"{base.rstrip('/')}/blobs/{quote(object_name.lstrip('/'), safe='/')}"


def resolve_plan(
    plan: ColumnPlan,
    published: Mapping[str, PublishedBlob],
) -> tuple[ColumnPlan, list[PublishedBlob]]:
    """Return a final plan with large literals mounted, plus its blobs."""
    task_plan = copy.deepcopy(plan)
    mounts: list[PublishedBlob] = []
    for entry in task_plan:
        if entry["kind"] != "literal":
            continue
        blob = literal_blob(entry)
        if blob is None:
            continue
        blob = published[blob.key]
        del entry["values"]
        entry["file"] = blob.mount_path
        mounts.append(blob)
    return task_plan, mounts


def _blob_entry(blob: PublishedBlob) -> dict[str, Any]:
    token = envs.LUMID_DATA_TOKEN
    if not token:
        raise RuntimeError("LUMID_DATA_TOKEN is required for LambdaOp task blobs")
    return {
        "url": blob_url(blob.object_name),
        "sha256": blob.sha256,
        "headers": {"Authorization": f"Bearer {token}"},
        "mountPath": blob.mount_path,
    }


def wrapper_source(
    op_id: str,
    fn_name: str,
    user_code: str,
    plan: ColumnPlan,
    mode: str = "row",
) -> str:
    """The python-task code for one standalone LambdaOp."""
    if mode == "list":
        main = _LIST_MAIN
    elif mode == "aligned":
        main = _ALIGNED_MAIN
    else:
        main = _ROW_MAIN
    return (_PRELUDE + main).format(
        op_id=op_id,
        module=TASK_RUNTIME_MODULE,
        mount=TASK_RUNTIME_MOUNT,
        code=user_code,
        fn_name=fn_name,
        plan=json.dumps(plan),
    )


def flowmesh_spec(
    node_id: str,
    data_spec: dict[str, Any],
    published_blobs: Mapping[str, PublishedBlob],
) -> dict[str, Any]:
    """The FlowMesh ``python`` task spec for a runtime python step."""
    plan, literal_mounts = resolve_plan(data_spec["plan"], published_blobs)
    mode = data_spec.get("mode", "row")
    if mode == "flatten":
        code = flatten_source(node_id, plan, data_spec["template"])
    elif mode == "regroup":
        code = regroup_source(node_id, plan)
    elif mode == "pairs":
        code = pairs_source(node_id, plan)
    elif mode == "row_skip_merge":
        code = row_skip_merge_code(node_id, plan, branch=data_spec["branch"])
    elif mode == "row_select":
        code = row_select_source(
            node_id,
            plan,
            labels=data_spec["labels"],
            branch=data_spec["branch"],
            include_done=data_spec.get("include_done", False),
        )
    elif mode == "row_status":
        code = row_status_source(
            node_id,
            plan,
            rules=data_spec["rules"],
            default_branch=data_spec["default_branch"],
            terminal_branch=data_spec.get("terminal_branch"),
        )
    else:
        code = wrapper_source(
            node_id, data_spec["fn_name"], data_spec["code"], plan, mode
        )
    spec: dict[str, Any] = {
        "taskType": TASK_TYPE,
        "code": code,
        "entrypoint": "main",
        "timeoutSeconds": data_spec["timeout_s"],
    }
    if data_spec.get("image"):
        spec["image"] = data_spec["image"]
    if data_spec.get("cache") is not None:
        spec["cache"] = data_spec["cache"]
    runtime = published_blobs[runtime_blob().key]
    spec["blobs"] = [_blob_entry(runtime)] + [
        _blob_entry(blob) for blob in literal_mounts
    ]
    stages = list(
        dict.fromkeys(entry["node"] for entry in plan if entry["kind"] == "stage")
    )
    if stages:
        spec["inputs"] = [{"stage": stage} for stage in stages]
    if "memory_mb" in data_spec:
        spec["resources"] = {"hardware": {"memory": f"{data_spec['memory_mb']}Mi"}}
    return spec
