def wrapper_source(
    op_id: str,
    fn_name: str,
    user_code: str,
    plan: ColumnPlan,
    mode: str = "row",
    by: str | None = None,
    on_fail: str = "fail_group",
    on_empty: str = LambdaOp.ON_EMPTY_DROP,
) -> str:
    """The python-task code for one standalone LambdaOp, seeded or not."""
    if mode == "list":
        main = _LIST_MAIN
    elif mode == "aligned":
        main = _ALIGNED_MAIN
    elif mode == "expand":
        main = _EXPAND_MAIN
    elif mode == "reduce":
        main = _REDUCE_MAIN
    else:
        main = _ROW_MAIN
    return (_PRELUDE + main).format(
        op_id=op_id,
        module=TASK_RUNTIME_MODULE,
        mount=TASK_RUNTIME_MOUNT,
        code=user_code,
        fn_name=fn_name,
        plan=plan_json(plan),
        by=by,
        on_fail=on_fail,
        on_empty=on_empty,
    )


def _required[T](value: T | None, field: str, mode: str) -> T:
    """A field a python step of ``mode`` must carry."""
    if value is None:
        raise ValueError(f"a {mode}-mode python step requires {field!r}")
    return value


def flowmesh_spec(
    node_id: str,
    data_spec: PythonData,
    published_blobs: Mapping[str, PublishedBlob],
) -> dict[str, Any]:
    """The FlowMesh ``python`` task spec for a runtime python step."""
    plan, literal_mounts = resolve_plan(data_spec.plan, published_blobs)
    mode = data_spec.mode or "row"
    if mode == "join":
        code = join_step.join_source(
            node_id,
            _required(data_spec.join, "join", mode),
            plan,
            TASK_RUNTIME_MOUNT,
        )
    elif mode == "flatten":
        code = flatten_source(
            node_id, plan, _required(data_spec.template, "template", mode)
        )
    elif mode == "regroup":
        code = regroup_source(node_id, plan)
    elif mode == "pairs":
        code = pairs_source(node_id, plan)
    elif mode == "flatten_step":
        code = flatten_step_source(node_id, plan)
    elif mode == "parse":
        code = parse_source(node_id, plan, _required(data_spec.parse, "parse", mode))
    else:
        code = wrapper_source(
            node_id,
            _required(data_spec.fn_name, "fn_name", mode),
            _required(data_spec.code, "code", mode),
            plan,
            mode,
            data_spec.by,
            data_spec.on_fail or "fail_group",
            data_spec.on_empty or LambdaOp.ON_EMPTY_DROP,
        )
    spec: dict[str, Any] = {
        "taskType": PYTHON_TASK_TYPE,
        "code": code,
        "entrypoint": "main",
        "timeoutSeconds": data_spec.timeout_s,
    }
    if data_spec.image:
        spec["image"] = data_spec.image
    if data_spec.cache is not None:
        spec["cache"] = data_spec.cache
    runtime = published_blobs[runtime_blob().key]
    spec["blobs"] = [_blob_entry(runtime)] + [
        _blob_entry(blob) for blob in literal_mounts
    ]
    stages = list(dict.fromkeys(entry.node for entry in plan if entry.kind == "stage"))
    if stages:
        spec["inputs"] = [{"stage": stage} for stage in stages]
    hardware: dict[str, Any] = {}
    if data_spec.memory_mb is not None:
        hardware["memory"] = f"{data_spec.memory_mb}Mi"
    if data_spec.gpu is not None:
        hardware["gpu"] = data_spec.gpu.model_dump(exclude_none=True)
    if hardware:
        spec["resources"] = {"hardware": hardware}
    return spec
