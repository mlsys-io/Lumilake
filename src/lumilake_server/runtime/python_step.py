"""Standalone Python steps: a LambdaOp that no LLM consumes.

A LambdaOp that is an output, or feeds only other LambdaOps, runs as its own
FlowMesh ``python`` task in a per-task container.
"""

import copy
import hashlib
import inspect
import json
from collections.abc import Mapping
from dataclasses import dataclass
from functools import cache
from typing import Any

from lumilake import envs
from lumilake_server.runtime import join_step, lambda_task_helpers
from lumilake_server.utils import lambda_runtime
from lumilake_server.utils.lumid_data_client import encode_blob_key

TASK_RUNTIME_MOUNT = "/mnt/blobs/lumilake-runtime.py"
TASK_RUNTIME_MODULE = "lumilake_runtime"
LITERAL_INLINE_MAX_BYTES = 1024
LITERAL_MOUNT_ROOT = "/mnt/blobs/literals"

TASK_TYPE = "python"
WHOLE_RESULT_MODES = ("list", "expand", "reduce")
BACKEND = "python"
DEFAULT_TIMEOUT_SECONDS = 600
MAX_BLOBS_PER_TASK = 16

# Column plan entries: {"kind": "stage", "node": <upstream node id>} or
# {"kind": "literal", "values": [...]}.
ColumnPlan = list[dict[str, Any]]


@dataclass(frozen=True)
class PublishedBlob:
    key: str
    object_name: str
    body: bytes
    content_type: str
    sha256: str
    mount_path: str


_PRELUDE = """\
# Generated by Lumilake for LambdaOp {op_id!r}. The caller's function is
# _USER_CODE; the mounted runtime adapts it to a FlowMesh python task.
import importlib.util
import json

_SPEC = importlib.util.spec_from_file_location({module!r}, {mount!r})
_RUNTIME = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(_RUNTIME)
_text = _RUNTIME._text
_column = _RUNTIME._column
_decode = _RUNTIME._decode
_walk_path = _RUNTIME._walk_path
_rows = _RUNTIME._rows
failure_of = _RUNTIME.failure_of
reject_reserved_key = _RUNTIME.reject_reserved_key
materialize = _RUNTIME.materialize

_USER_CODE = {code!r}
_FN_NAME = {fn_name!r}
_NODE = {op_id!r}
_PLAN = json.loads({plan!r})
"""

_RESHAPE_PRELUDE = """\
# Generated by Lumilake for {op_id!r}: a flatten/regroup reshape step.
import importlib.util
import json

_SPEC = importlib.util.spec_from_file_location({module!r}, {mount!r})
_RUNTIME = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(_RUNTIME)
_text = _RUNTIME._text
_column = _RUNTIME._column
failure_of = _RUNTIME.failure_of
_NODE = {op_id!r}
_PLAN = json.loads({plan!r})
"""

_FLATTEN_MAIN = """\

_TEMPLATE = {template!r}

def main(inputs):
    columns = [_column(entry, inputs, _text) for entry in _PLAN]
    grouped = [c for c, e in zip(columns, _PLAN) if e.get("grouped")]
    row_level = [c for c, e in zip(columns, _PLAN) if not e.get("grouped")]
    n = len(grouped[0])
    group_sizes = [len(g) for g in grouped[0]]
    for entry, col in zip(_PLAN, columns):
        label = entry.get("label")
        if entry.get("grouped"):
            if len(col) != n:
                raise ValueError(
                    "%s: flatten grouped column %r has %d groups; expected %d"
                    % (_NODE, label, len(col), n)
                )
            for i, group in enumerate(col):
                if len(group) != group_sizes[i]:
                    raise ValueError(
                        "%s: flatten grouped column %r row %d has %d values; "
                        "expected %d" % (_NODE, label, i, len(group), group_sizes[i])
                    )
        elif len(col) not in (1, n):
            raise ValueError(
                "%s: flatten row-level column %r has %d values; expected 1 or %d"
                % (_NODE, label, len(col), n)
            )
    items = []
    for i in range(n):
        size = group_sizes[i]
        for j in range(size):
            values = {{}}
            for entry, col in zip(_PLAN, columns):
                if entry is _PLAN[0]:
                    # The image entry (always first) is the group boundary; its
                    # content is never rendered into the prompt.
                    continue
                label = entry.get("label")
                if entry.get("grouped"):
                    values[label] = col[i][j]
                else:
                    values[label] = col[i] if len(col) == n else col[0]
            prompt = _TEMPLATE.format_map(
                {{k: _text(v) for k, v in values.items()}}
            )
            items.append({{"output": prompt, "row": i}})
    return {{"items": items}}
"""

_REGROUP_MAIN = """\

def main(inputs):
    columns = [_column(entry, inputs, _text) for entry in _PLAN]
    values = columns[0]
    rows = columns[1]
    groups = columns[2]
    n = len(groups)
    if len(values) != len(rows):
        raise ValueError(
            "%s: regroup has %d outputs but %d rows" % (_NODE, len(values), len(rows))
        )
    result = [[] for _ in range(n)]
    for value, row in zip(values, rows):
        if not isinstance(row, int):
            raise ValueError("%s: regroup row %r is not an integer" % (_NODE, row))
        if not 0 <= row < n:
            raise ValueError(
                "%s: regroup row %d out of range for %d symbols" % (_NODE, row, n)
            )
        result[row].append(value)
    for r in range(n):
        if len(result[r]) != len(groups[r]):
            raise ValueError(
                "%s: regroup row %d has %d outputs; expected %d"
                % (_NODE, r, len(result[r]), len(groups[r]))
            )
    return {{"items": [{{"output": result[r]}} for r in range(n)]}}
"""

_ROW_MAIN = """\

def main(inputs):
    fn = materialize(_USER_CODE, _FN_NAME)
    columns = [_column(entry, inputs, _text) for entry in _PLAN]
    n = max((len(c) for c in columns), default=1)
    for entry, col in zip(_PLAN, columns):
        if len(col) not in (1, n):
            raise ValueError(
                "input %r has %d rows; expected 1 or %d"
                % (entry.get("node", "literal"), len(col), n)
            )
    rows = [tuple(c[0] if len(c) == 1 else c[i] for c in columns) for i in range(n)]
    items = []
    for row in rows:
        marked = next(
            (value for value in map(failure_of, row) if value is not None), None
        )
        if marked is not None:
            # A row with a marked cell is not passed to the function: the
            # record keeps its position and carries the marker onward.
            items.append({{"output": marked, "value": marked}})
            continue
        value = fn(row)
        reject_reserved_key(value, _NODE)
        items.append({{"output": _text(value), "value": value}})
    return {{"items": items}}
"""

_LIST_MAIN = """\

def main(inputs):
    fn = materialize(_USER_CODE, _FN_NAME)
    columns = [_column(entry, inputs, lambda v: v) for entry in _PLAN]
    values = fn(tuple(columns))
    for value in values:
        reject_reserved_key(value, _NODE)
    return {{"items": [{{"output": v}} for v in values]}}
"""

_ALIGNED_MAIN = """\

def main(inputs):
    fn = materialize(_USER_CODE, _FN_NAME)
    columns = [_column(entry, inputs, lambda v: v) for entry in _PLAN]
    n = max((len(c) for c in columns), default=0)
    for entry, col in zip(_PLAN, columns):
        if len(col) not in (1, n):
            raise ValueError(
                "input %r has %d rows; expected 1 or %d"
                % (entry.get("node", "literal"), len(col), n)
            )
    rows = (
        tuple(c[0] if len(c) == 1 else c[i] for c in columns) for i in range(n)
    )
    marked = [
        next((value for value in map(failure_of, row) if value is not None), None)
        for row in rows
    ]
    live = [i for i, marker in enumerate(marked) if marker is None]
    live_columns = tuple(
        col if len(col) == 1 else [col[i] for i in live] for col in columns
    )
    values = fn(live_columns)
    if len(values) != len(live):
        raise ValueError(
            "aligned lambda {op_id!r} returned %d values for %d rows"
            % (len(values), len(live))
        )
    merged = marked.copy()
    for i, value in zip(live, values):
        reject_reserved_key(value, _NODE, i)
        merged[i] = value
    return {{"items": [{{"output": v}} for v in merged]}}
"""


_EXPAND_MAIN = """\

def main(inputs):
    fn = materialize(_USER_CODE, _FN_NAME)
    columns = [
        [_decode(v) for v in _column(entry, inputs, lambda v: v)]
        for entry in _PLAN
    ]
    items = []
    for row in _rows(columns, _PLAN, {op_id!r}):
        values = fn(row)
        if not isinstance(values, list):
            raise ValueError(
                "%s: expand lambda %r returned %s; expected a list"
                % ({op_id!r}, _FN_NAME, type(values).__name__)
            )
        items.extend({{"output": v}} for v in values)
    return {{"items": items}}
"""

_REDUCE_MAIN = """\

_BY = {by!r}
_BY_PATH = _BY.split(".")

def main(inputs):
    fn = materialize(_USER_CODE, _FN_NAME)
    columns = [
        [_decode(v) for v in _column(entry, inputs, lambda v: v)]
        for entry in _PLAN
    ]
    groups = {{}}
    for i, row in enumerate(_rows(columns, _PLAN, {op_id!r})):
        try:
            key = json.dumps(
                _walk_path(row[0], _BY_PATH, "row %d" % i), sort_keys=True
            )
        except ValueError as exc:
            raise ValueError(
                "%s: reduce lambda cannot group row %d by %r: %s"
                % ({op_id!r}, i, _BY, exc)
            ) from exc
        groups.setdefault(key, []).append(row)
    return {{"items": [{{"output": fn(rows)}} for rows in groups.values()]}}
"""


_PAIRS_MAIN = """\

def main(inputs):
    columns = [_column(entry, inputs, lambda v: v) for entry in _PLAN]
    queries, candidates = columns
    for name, values in (("query", queries), ("candidate", candidates)):
        if not values:
            raise ValueError(
                "%s: %s column is empty; classification needs at least one pair"
                % (_NODE, name)
            )
    if len(queries) == 1:
        queries = queries * len(candidates)
    if len(queries) != len(candidates):
        raise ValueError(
            "%s: query column has %d values but candidate column has %d"
            % (_NODE, len(queries), len(candidates))
        )
    for row, (query, candidate) in enumerate(zip(queries, candidates)):
        for name, value in (("query", query), ("candidate", candidate)):
            if not isinstance(value, str) or not value.strip():
                raise ValueError(
                    "%s: row %d %s must be a non-empty string, got %r"
                    % (_NODE, row, name, value)
                )
    return {{"items": [
        {{"text": query, "text_pair": candidate}}
        for query, candidate in zip(queries, candidates)
    ]}}
"""


def flatten_source(node_id: str, plan: ColumnPlan, template: str) -> str:
    """The python-task code for a flatten step: one rendered prompt per image."""
    return (_RESHAPE_PRELUDE + _FLATTEN_MAIN).format(
        op_id=node_id,
        module=TASK_RUNTIME_MODULE,
        mount=TASK_RUNTIME_MOUNT,
        plan=json.dumps(plan),
        template=template,
    )


