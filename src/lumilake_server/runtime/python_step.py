_FLATTEN_MAIN = """\

_TEMPLATE = {template!r}

def main(inputs):
    columns = [_column(entry, inputs, text) for entry in _PLAN]
    grouped = [c for c, e in zip(columns, _PLAN) if e.get("grouped")]
    row_level = [c for c, e in zip(columns, _PLAN) if not e.get("grouped")]
    n = len(grouped[0])
    group_sizes = [len(g) for g in grouped[0]]
    for entry, col in zip(_PLAN, columns):
        label = entry.get("label")
        if entry.get("grouped"):
            if len(col) != n:
                raise ValueError(
                    "%s: flatten grouped column %r has %d groups; expected %d"
                    % (_NODE, label, len(col), n)
                )
            for i, group in enumerate(col):
                if len(group) != group_sizes[i]:
                    raise ValueError(
                        "%s: flatten grouped column %r row %d has %d values; "
                        "expected %d" % (_NODE, label, i, len(group), group_sizes[i])
                    )
        elif len(col) not in (1, n):
            raise ValueError(
                "%s: flatten row-level column %r has %d values; expected 1 or %d"
                % (_NODE, label, len(col), n)
            )
    items = []
    for i in range(n):
        size = group_sizes[i]
        for j in range(size):
            values = {{}}
            for entry, col in zip(_PLAN, columns):
                if entry is _PLAN[0]:
                    # The image entry (always first) is the group boundary; its
                    # content is never rendered into the prompt.
                    continue
                label = entry.get("label")
                if entry.get("grouped"):
                    values[label] = col[i][j]
                else:
                    values[label] = col[i] if len(col) == n else col[0]
            prompt = _TEMPLATE.format_map(
                {{k: text(v) for k, v in values.items()}}
            )
            items.append({{"output": prompt, "row": i}})
    return {{"items": items}}
"""

_REGROUP_MAIN = """\

def main(inputs):
    columns = [_column(entry, inputs, text) for entry in _PLAN]
    values = columns[0]
    rows = columns[1]
    groups = columns[2]
    n = len(groups)
    if len(values) != len(rows):
        raise ValueError(
            "%s: regroup has %d outputs but %d rows" % (_NODE, len(values), len(rows))
        )
    result = [[] for _ in range(n)]
    for value, row in zip(values, rows):
        if not isinstance(row, int):
            raise ValueError("%s: regroup row %r is not an integer" % (_NODE, row))
        if not 0 <= row < n:
            raise ValueError(
                "%s: regroup row %d out of range for %d symbols" % (_NODE, row, n)
            )
        result[row].append(value)
    for r in range(n):
        if len(result[r]) != len(groups[r]):
            raise ValueError(
                "%s: regroup row %d has %d outputs; expected %d"
                % (_NODE, r, len(result[r]), len(groups[r]))
            )
    return {{"items": [{{"output": result[r]}} for r in range(n)]}}
"""

_ROW_MAIN = """\

def main(inputs):
    (seed_entry,) = [e for e in _PLAN if e.get("role") == "seed"] or [None]
    fn = materialize(_USER_CODE, _FN_NAME, 1 if seed_entry is None else 2)
    data = [entry for entry in _PLAN if entry.get("role") != "seed"]
    columns = [_column(entry, inputs, decode) for entry in data]
    n = max((len(c) for c in columns), default=1)
    for entry, col in zip(data, columns):
        if len(col) not in (1, n):
            raise ValueError(
                "input %r has %d rows; expected 1 or %d"
                % (entry.get("node", "literal"), len(col), n)
            )
    rows = [tuple(c[0] if len(c) == 1 else c[i] for c in columns) for i in range(n)]
    cells = None
    seeds = None
    if seed_entry is not None:
        cells = _column(seed_entry, inputs, text)
        # A marked seed cell marks its row and is never read as a draw.
        seeds = [
            None
            if failure_of(cells[i]) is not None
            else _raw_seed(cells[i], {op_id!r}, i)
            for i in range(len(cells))
        ]
        if len(seeds) != n:
            raise ValueError(
                "%s: seed column has %d rows; expected one per row, so %d"
                % ({op_id!r}, len(seeds), n)
            )
    items = []
    for i, row in enumerate(rows):
        marked = next(
            (value for value in map(failure_of, row) if value is not None), None
        )
        if marked is None and seeds is not None and seeds[i] is None:
            marked = failure_of(cells[i])
        if marked is not None:
            # A marked row keeps its position and passes the marker on.
            items.append({{"output": marked, "value": marked}})
            continue
        value = fn(row) if seeds is None else fn(row, seeds[i])
        reject_reserved_key(value, _NODE)
        items.append({{"output": text(value), "value": value}})
    return {{"items": items}}
"""

_LIST_MAIN = """\

def main(inputs):
    fn = materialize(_USER_CODE, _FN_NAME)
    columns = [_column(entry, inputs, decode) for entry in _PLAN]
    values = fn(tuple(columns))
    # A received marker may come back decoded, so it counts as received too.
    received = tuple(value for column in columns for value in column)
    originals = received + tuple(
        marker for marker in map(failure_of, received) if marker is not None
    )
    items = []
    for value in values:
        reject_reserved_key(value, _NODE, originals=originals)
        items.append({{"output": value}})
    return {{"items": items}}
"""

_ALIGNED_MAIN = """\

def main(inputs):
    fn = materialize(_USER_CODE, _FN_NAME)
    columns = [_column(entry, inputs, decode) for entry in _PLAN]
    n = max((len(c) for c in columns), default=0)
    for entry, col in zip(_PLAN, columns):
        if len(col) not in (1, n):
            raise ValueError(
                "input %r has %d rows; expected 1 or %d"
                % (entry.get("node", "literal"), len(col), n)
            )
    rows = (
        tuple(c[0] if len(c) == 1 else c[i] for c in columns) for i in range(n)
    )
    marked = [
        next((value for value in map(failure_of, row) if value is not None), None)
        for row in rows
    ]
    live = [i for i, marker in enumerate(marked) if marker is None]
    if not live:
        # Every row is marked, so the function has no live row.
        return {{"items": [{{"output": marker}} for marker in marked]}}
    live_columns = tuple(
        col if len(col) == 1 and n > 1 else [col[i] for i in live]
        for col in columns
    )
    values = fn(live_columns)
    if len(values) != len(live):
        raise ValueError(
            "aligned lambda {op_id!r} returned %d values for %d rows"
            % (len(values), len(live))
        )
    merged = marked.copy()
    originals = tuple(value for column in columns for value in column)
    for i, value in zip(live, values):
        reject_reserved_key(value, _NODE, i, originals)
        merged[i] = value
    return {{"items": [{{"output": v}} for v in merged]}}
"""


_EXPAND_MAIN = """\

_ON_EMPTY = {on_empty!r}

def main(inputs):
    (seed_entry,) = [e for e in _PLAN if e.get("role") == "seed"] or [None]
    fn = materialize(_USER_CODE, _FN_NAME, 1 if seed_entry is None else 2)
    data = [entry for entry in _PLAN if entry.get("role") != "seed"]
    columns = [_column(entry, inputs, decode) for entry in data]
    rows = _rows(columns, data, {op_id!r})
    cells = None
    seeds = None
    if seed_entry is not None:
        cells = _column(seed_entry, inputs, text)
        # A marked seed cell marks its row and is never read as a draw.
        seeds = [
            None
            if failure_of(cells[i]) is not None
            else _raw_seed(cells[i], {op_id!r}, i)
            for i in range(len(cells))
        ]
        if len(seeds) != len(rows):
            raise ValueError(
                "%s: seed column has %d rows; expected one per row, so %d"
                % ({op_id!r}, len(seeds), len(rows))
            )
    items = []
    for index, row in enumerate(rows):
        marked = carried_marker(row)
        if marked is None and seeds is not None and seeds[index] is None:
            marked = failure_of(cells[index])
        if marked is not None:
            # A marked row keeps its slot and carries the marker onward.
            items.append({{"output": marked, "parent": index, "child": 0}})
            continue
        values = fn(row) if seeds is None else fn(row, seeds[index])
        if not isinstance(values, list):
            raise ValueError(
                "%s: expand lambda %r returned %s; expected a list"
                % ({op_id!r}, _FN_NAME, type(values).__name__)
            )
        if not values and _ON_EMPTY == "fail":
            # An empty expansion emits a marker, not nothing at all.
            items.append(
                {{
                    "output": {{
                        "_fail": {{"op": {op_id!r}, "reason": "empty expansion"}}
                    }},
                    "parent": index,
                    "child": 0,
                }}
            )
            continue
        items.extend(
            {{"output": v, "parent": index, "child": child}}
            for child, v in enumerate(values)
        )
    return {{"items": items}}
"""


_REDUCE_MAIN = """\

_BY = {by!r}
_BY_PATH = _BY.split(".")
_ON_FAIL = {on_fail!r}

def main(inputs):
    fn = materialize(_USER_CODE, _FN_NAME)
    columns = [_column(entry, inputs, decode) for entry in _PLAN]
    entries = []
    by_key = {{}}
    for i, row in enumerate(_rows(columns, _PLAN, {op_id!r})):
        try:
            value = _walk_path(row[0], _BY_PATH, "row %d" % i)
        except ValueError as exc:
            marker = carried_marker(row)
            if marker is None:
                raise ValueError(
                    "%s: reduce lambda cannot group row %d by %r: %s"
                    % ({op_id!r}, i, _BY, exc)
                ) from exc
            # Only a row whose key cannot be read has no key: it is the marker itself,
            # or the key path reaches one. Its group is itself, and it emits that
            # marker.
            entries.append((None, [row], marker))
            continue
        marker = failure_of(value)
        if marker is not None:
            entries.append((None, [row], marker))
            continue
        key = json.dumps(value, sort_keys=True)
        if key not in by_key:
            by_key[key] = len(entries)
            entries.append((key, [], None))
        entries[by_key[key]][1].append(row)
    items = []
    for key, rows, own in entries:
        if own is not None:
            # The group is the one row without a key, and it emits its marker, which
            # names the op that failed rather than this one.
            items.append({{"output": own}})
            continue
        markers = [m for m in map(carried_marker, rows) if m is not None]
        if markers:
            if _ON_FAIL == "fail_group":
                items.append({{"output": markers[0]}})
                continue
            rows = [row for row in rows if carried_marker(row) is None]
            if not rows:
                items.append(
                    {{
                        "output": {{
                            "_fail": {{"op": {op_id!r}, "reason": "empty group"}}
                        }}
                    }}
                )
                continue
        items.append({{"output": fn(rows)}})
    return {{"items": items}}
"""


_PAIRS_MAIN = """\

def main(inputs):
    columns = [_column(entry, inputs, lambda v: v) for entry in _PLAN]
    queries, candidates = columns
    for name, values in (("query", queries), ("candidate", candidates)):
        if not values:
            raise ValueError(
                "%s: %s column is empty; classification needs at least one pair"
                % (_NODE, name)
            )
    if len(queries) == 1:
        queries = queries * len(candidates)
    if len(queries) != len(candidates):
        raise ValueError(
            "%s: query column has %d values but candidate column has %d"
            % (_NODE, len(queries), len(candidates))
        )
    for row, (query, candidate) in enumerate(zip(queries, candidates)):
        for name, value in (("query", query), ("candidate", candidate)):
            if not isinstance(value, str) or not value.strip():
                raise ValueError(
                    "%s: row %d %s must be a non-empty string, got %r"
                    % (_NODE, row, name, value)
                )
    return {{"items": [
        {{"text": query, "text_pair": candidate}}
        for query, candidate in zip(queries, candidates)
    ]}}
"""


