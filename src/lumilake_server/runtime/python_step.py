"""Standalone Python steps: a LambdaOp that no LLM consumes.

A LambdaOp that is an output, or feeds only other LambdaOps, runs as its own
FlowMesh ``python`` task in a per-task container.
"""

import hashlib
import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any
from urllib.parse import quote

from lumilake import envs

TASK_RUNTIME_MOUNT = "/mnt/blobs/lumilake-runtime.py"
TASK_RUNTIME_MODULE = "lumilake_runtime"
LITERAL_INLINE_MAX_BYTES = 1024
LITERAL_MOUNT_ROOT = "/mnt/blobs/literals"

TASK_TYPE = "python"
BACKEND = "python"
DEFAULT_TIMEOUT_SECONDS = 600

# Column plan entries: {"kind": "stage", "node": <upstream node id>} or
# {"kind": "literal", "values": [...]}.
ColumnPlan = list[dict[str, Any]]

_PRELUDE = """\
# Generated by Lumilake for LambdaOp {op_id!r}. The caller's function is
# _USER_CODE; the mounted runtime adapts it to a FlowMesh python task.
import importlib.util
import json

_SPEC = importlib.util.spec_from_file_location({module!r}, {mount!r})
_RUNTIME = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(_RUNTIME)
_text = _RUNTIME._text
_column = _RUNTIME._column
materialize = _RUNTIME.materialize

_USER_CODE = {code!r}
_FN_NAME = {fn_name!r}
_PLAN = json.loads({plan!r})
"""

_RESHAPE_PRELUDE = """\
# Generated by Lumilake for {op_id!r}: a flatten/regroup reshape step.
import importlib.util
import json

_SPEC = importlib.util.spec_from_file_location({module!r}, {mount!r})
_RUNTIME = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(_RUNTIME)
_text = _RUNTIME._text
_column = _RUNTIME._column
_NODE = {op_id!r}
_PLAN = json.loads({plan!r})
"""

_FLATTEN_MAIN = """\

_TEMPLATE = {template!r}

def main(inputs):
    columns = [_column(entry, inputs, _text) for entry in _PLAN]
    grouped = [c for c, e in zip(columns, _PLAN) if e.get("grouped")]
    row_level = [c for c, e in zip(columns, _PLAN) if not e.get("grouped")]
    n = len(grouped[0])
    group_sizes = [len(g) for g in grouped[0]]
    for entry, col in zip(_PLAN, columns):
        label = entry.get("label")
        if entry.get("grouped"):
            if len(col) != n:
                raise ValueError(
                    "%s: flatten grouped column %r has %d groups; expected %d"
                    % (_NODE, label, len(col), n)
                )
            for i, group in enumerate(col):
                if len(group) != group_sizes[i]:
                    raise ValueError(
                        "%s: flatten grouped column %r row %d has %d values; "
                        "expected %d" % (_NODE, label, i, len(group), group_sizes[i])
                    )
        elif len(col) not in (1, n):
            raise ValueError(
                "%s: flatten row-level column %r has %d values; expected 1 or %d"
                % (_NODE, label, len(col), n)
            )
    items = []
    for i in range(n):
        size = group_sizes[i]
        for j in range(size):
            values = {{}}
            for entry, col in zip(_PLAN, columns):
                if entry is _PLAN[0]:
                    # The image entry (always first) is the group boundary; its
                    # content is never rendered into the prompt.
                    continue
                label = entry.get("label")
                if entry.get("grouped"):
                    values[label] = col[i][j]
                else:
                    values[label] = col[i] if len(col) == n else col[0]
            prompt = _TEMPLATE.format_map(
                {{k: _text(v) for k, v in values.items()}}
            )
            items.append({{"output": prompt, "row": i}})
    return {{"items": items}}
"""

_REGROUP_MAIN = """\

def main(inputs):
    columns = [_column(entry, inputs, _text) for entry in _PLAN]
    values = columns[0]
    rows = columns[1]
    groups = columns[2]
    n = len(groups)
    if len(values) != len(rows):
        raise ValueError(
            "%s: regroup has %d outputs but %d rows" % (_NODE, len(values), len(rows))
        )
    result = [[] for _ in range(n)]
    for value, row in zip(values, rows):
        if not isinstance(row, int):
            raise ValueError("%s: regroup row %r is not an integer" % (_NODE, row))
        if not 0 <= row < n:
            raise ValueError(
                "%s: regroup row %d out of range for %d symbols" % (_NODE, row, n)
            )
        result[row].append(value)
    for r in range(n):
        if len(result[r]) != len(groups[r]):
            raise ValueError(
                "%s: regroup row %d has %d outputs; expected %d"
                % (_NODE, r, len(result[r]), len(groups[r]))
            )
    return {{"items": [{{"output": result[r]}} for r in range(n)]}}
"""

_ROW_MAIN = """\

def main(inputs):
    fn = materialize(_USER_CODE, _FN_NAME)
    columns = [_column(entry, inputs, _text) for entry in _PLAN]
    n = max((len(c) for c in columns), default=1)
    for entry, col in zip(_PLAN, columns):
        if len(col) not in (1, n):
            raise ValueError(
                "input %r has %d rows; expected 1 or %d"
                % (entry.get("node", "literal"), len(col), n)
            )
    rows = [tuple(c[0] if len(c) == 1 else c[i] for c in columns) for i in range(n)]
    return {{
        "items": [
            {{"output": _text(r), "value": r}}
            for r in (fn(row) for row in rows)
        ]
    }}
"""

_LIST_MAIN = """\

def main(inputs):
    fn = materialize(_USER_CODE, _FN_NAME)
    columns = [_column(entry, inputs, lambda v: v) for entry in _PLAN]
    values = fn(tuple(columns))
    return {{"items": [{{"output": v}} for v in values]}}
"""

_ALIGNED_MAIN = """\

def main(inputs):
    fn = materialize(_USER_CODE, _FN_NAME)
    columns = [_column(entry, inputs, lambda v: v) for entry in _PLAN]
    n = max((len(c) for c in columns), default=0)
    for entry, col in zip(_PLAN, columns):
        if len(col) not in (1, n):
            raise ValueError(
                "input %r has %d rows; expected 1 or %d"
                % (entry.get("node", "literal"), len(col), n)
            )
    values = fn(tuple(columns))
    if len(values) != n:
        raise ValueError(
            "aligned lambda {op_id!r} returned %d values for %d rows"
            % (len(values), n)
        )
    return {{"items": [{{"output": v}} for v in values]}}
"""


def flatten_source(node_id: str, plan: ColumnPlan, template: str) -> str:
    """The python-task code for a flatten step: one rendered prompt per image."""
    return (_RESHAPE_PRELUDE + _FLATTEN_MAIN).format(
        op_id=node_id,
        module=TASK_RUNTIME_MODULE,
        mount=TASK_RUNTIME_MOUNT,
        plan=json.dumps(plan),
        template=template,
    )


def regroup_source(node_id: str, plan: ColumnPlan) -> str:
    """The python-task code for a regroup step: outputs back to one item per
    symbol."""
    return (_RESHAPE_PRELUDE + _REGROUP_MAIN).format(
        op_id=node_id,
        module=TASK_RUNTIME_MODULE,
        mount=TASK_RUNTIME_MOUNT,
        plan=json.dumps(plan),
    )


def runtime_bytes() -> bytes:
    """The worker-side runtime source mounted by every generated task."""
    path = Path(__file__).with_name("lambda_task_runtime.py")
    return path.read_bytes()


def runtime_blob_entry() -> dict[str, Any]:
    mount_path = TASK_RUNTIME_MOUNT
    return {
        "mountPath": mount_path,
        "blobKey": f"lambda-runtime/{hashlib.sha256(runtime_bytes()).hexdigest()}.py",
    }


def literal_blobs(plan: ColumnPlan) -> dict[str, bytes]:
    """Content-addressed JSON blobs for literal payloads above the inline cutoff."""
    blobs: dict[str, bytes] = {}
    for entry in plan:
        if entry["kind"] != "literal" or "values" not in entry:
            continue
        encoded = json.dumps(entry["values"], ensure_ascii=False).encode("utf-8")
        if len(encoded) <= LITERAL_INLINE_MAX_BYTES:
            continue
        digest = hashlib.sha256(encoded).hexdigest()
        blobs[f"literals/{digest}.json"] = encoded
    return blobs


def runtime_blob_url(blob_key: str) -> str:
    base = envs.LUMID_DATA_WORKER_URL or envs.LUMID_DATA_URL
    if not base:
        raise RuntimeError("LUMID_DATA_URL is required for LambdaOp task blobs")
    return f"{base.rstrip('/')}/blobs/{quote(blob_key.lstrip('/'), safe='/')}"


def bind_runtime_blob(spec: dict[str, Any], blob_url: str) -> None:
    runtime_blob = runtime_blob_entry()
    blob_key = runtime_blob["blobKey"]
    existing = [
        blob
        for blob in (spec.get("blobs") or [])
        if not blob.get("blobKey", "").startswith("lambda-runtime/")
    ]
    spec["blobs"] = [
        {
            "url": blob_url,
            "sha256": blob_key.rsplit("/", 1)[-1].removesuffix(".py"),
            "headers": {"Authorization": f"Bearer {envs.LUMID_DATA_TOKEN}"},
            "mountPath": runtime_blob["mountPath"],
        }
    ] + existing


def bind_blob_urls(
    node_id: str,
    spec: dict[str, Any],
    *,
    plan: ColumnPlan,
    blob_urls: Mapping[str, str],
) -> None:
    runtime_blob = runtime_blob_entry()
    runtime_key = runtime_blob["blobKey"]
    if runtime_key not in blob_urls:
        raise RuntimeError(f"python task blob {runtime_key!r} was not published")
    bind_runtime_blob(spec, blob_urls[runtime_key])
    if plan:
        bind_literal_blobs(node_id, spec, plan=plan, blob_urls=blob_urls)


def bind_literal_blobs(
    node_id: str,
    spec: dict[str, Any],
    *,
    plan: ColumnPlan,
    blob_urls: Mapping[str, str],
) -> None:
    """Move large literal payloads into mounted JSON files in the task code."""
    code = spec["code"]
    task_plan = json.loads(json.dumps(plan))
    for entry in task_plan:
        if entry["kind"] != "literal" or "values" not in entry:
            continue
        encoded = json.dumps(entry["values"], ensure_ascii=False).encode("utf-8")
        if len(encoded) <= LITERAL_INLINE_MAX_BYTES:
            continue
        digest = hashlib.sha256(encoded).hexdigest()
        key = f"literals/{digest}.json"
        if key not in blob_urls:
            raise RuntimeError(f"literal blob {key!r} was not published")
        mount_path = f"{LITERAL_MOUNT_ROOT}/{digest}.json"
        entry.pop("values", None)
        entry["path"] = mount_path
        existing = spec.get("blobs") or []
        spec["blobs"] = existing + [
            {
                "url": blob_urls[key],
                "sha256": digest,
                "headers": {"Authorization": f"Bearer {envs.LUMID_DATA_TOKEN}"},
                "mountPath": mount_path,
            }
        ]
    if task_plan != plan:
        spec["code"] = code.replace(
            f"_PLAN = json.loads({json.dumps(plan)!r})",
            f"_PLAN = json.loads({json.dumps(task_plan)!r})",
            1,
        )


def wrapper_source(
    op_id: str,
    fn_name: str,
    user_code: str,
    plan: ColumnPlan,
    mode: str = "row",
    *,
    runtime_mount: str = TASK_RUNTIME_MOUNT,
) -> str:
    """The python-task code for one standalone LambdaOp."""
    if mode == "list":
        main = _LIST_MAIN
    elif mode == "aligned":
        main = _ALIGNED_MAIN
    else:
        main = _ROW_MAIN
    return (_PRELUDE + main).format(
        op_id=op_id,
        module=TASK_RUNTIME_MODULE,
        mount=runtime_mount,
        code=user_code,
        fn_name=fn_name,
        plan=json.dumps(plan),
    )


def flowmesh_spec(
    node_id: str,
    data_spec: dict[str, Any],
    *,
    blob_urls: Mapping[str, str] | None = None,
) -> dict[str, Any]:
    """The FlowMesh ``python`` task spec for a runtime python step."""
    plan: ColumnPlan = data_spec["plan"]
    mode = data_spec.get("mode", "row")
    if mode == "flatten":
        code = flatten_source(node_id, plan, data_spec["template"])
    elif mode == "regroup":
        code = regroup_source(node_id, plan)
    else:
        code = wrapper_source(
            node_id, data_spec["fn_name"], data_spec["code"], plan, mode
        )
    spec: dict[str, Any] = {
        "taskType": TASK_TYPE,
        "code": code,
        "entrypoint": "main",
        "timeoutSeconds": data_spec["timeout_s"],
    }
    if data_spec.get("image"):
        spec["image"] = data_spec["image"]
    if data_spec.get("cache") is not None:
        spec["cache"] = data_spec["cache"]
    runtime_blob = runtime_blob_entry()
    blob_key = runtime_blob["blobKey"]
    if blob_key in (blob_urls or {}):
        spec["blobs"] = [
            {
                "url": (blob_urls or {})[blob_key],
                "sha256": blob_key.rsplit("/", 1)[-1].removesuffix(".py"),
                "headers": {"Authorization": f"Bearer {envs.LUMID_DATA_TOKEN}"},
                "mountPath": TASK_RUNTIME_MOUNT,
            }
        ]
    else:
        spec["blobs"] = [runtime_blob]
    stages = list(
        dict.fromkeys(entry["node"] for entry in plan if entry["kind"] == "stage")
    )
    if stages:
        spec["inputs"] = [{"stage": stage} for stage in stages]
    if "memory_mb" in data_spec:
        spec["resources"] = {"hardware": {"memory": f"{data_spec['memory_mb']}Mi"}}
    return spec
